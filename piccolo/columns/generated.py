from __future__ import annotations

from abc import ABC, abstractmethod
from typing import Optional

from piccolo.utils.repr import repr_class_instance


class Generated(ABC):
    """
    The base class for anything which can be passed to a column's
    ``generated`` argument.
    """

    @property
    @abstractmethod
    def postgres(self) -> str:
        pass

    @property
    @abstractmethod
    def cockroach(self) -> str:
        pass

    @property
    @abstractmethod
    def sqlite(self) -> str:
        pass

    @property
    def writable(self) -> bool:
        """
        Whether the database lets us write our own values to the column.
        """
        return False

    def __repr__(self):
        return repr_class_instance(self)

    def __str__(self):
        return self.__repr__()

    def __eq__(self, other):
        return self.__hash__() == other.__hash__()

    def __hash__(self):
        return hash(self.__str__())


class Identity(Generated):
    def __init__(
        self,
        always: bool = True,
        start: Optional[int] = None,
        increment: Optional[int] = None,
    ):
        """
        Makes an integer column an identity column, which is the recommended
        alternative to ``SERIAL`` in Postgres
        (`see docs <https://www.postgresql.org/docs/current/ddl-identity-columns.html>`_).

        .. code-block:: python

            class Band(Table):
                id = BigInt(primary_key=True, generated=Identity())

        :param always:
            If ``True``, the database always generates the value, and
            raises an error if you try to insert your own value
            (``GENERATED ALWAYS AS IDENTITY``). If ``False``, the database
            only generates the value if you don't provide one
            (``GENERATED BY DEFAULT AS IDENTITY``).
        :param start:
            The first value in the sequence.
        :param increment:
            How much the sequence goes up by each time.

        """  # noqa: E501
        if start is not None and not isinstance(start, int):
            raise ValueError("`start` must be an integer.")

        if increment is not None:
            if not isinstance(increment, int):
                raise ValueError("`increment` must be an integer.")
            if increment == 0:
                raise ValueError("`increment` can't be 0.")

        self.always = always
        self.start = start
        self.increment = increment

    def _get_sql(self) -> str:
        mode = "ALWAYS" if self.always else "BY DEFAULT"
        sql = f"GENERATED {mode} AS IDENTITY"

        sequence_options = []
        if self.start is not None:
            sequence_options.append(f"START WITH {self.start}")
        if self.increment is not None:
            sequence_options.append(f"INCREMENT BY {self.increment}")

        if sequence_options:
            sql += f" ({' '.join(sequence_options)})"

        return sql

    @property
    def writable(self) -> bool:
        # `GENERATED BY DEFAULT` columns accept user supplied values.
        return not self.always

    @property
    def postgres(self) -> str:
        return self._get_sql()

    @property
    def cockroach(self) -> str:
        return self._get_sql()

    @property
    def sqlite(self) -> str:
        # SQLite doesn't support identity columns. An `INTEGER PRIMARY KEY`
        # column is already autoincrementing, so we don't need anything.
        return ""


__all__ = ["Generated", "Identity"]
